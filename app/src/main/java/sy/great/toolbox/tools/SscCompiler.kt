package sy.great.toolbox.tools

import android.content.Context
import java.io.File
import java.io.FileOutputStream
import java.util.concurrent.TimeUnit

/**
 * SSC 脚本编译器：把 Shell 脚本编译成可执行 ELF。
 *
 * 原理（与 SSC 官方一致）：
 *   SSC 不是把 Shell 语义编译成机器码的编译器。
 *   它的做法是生成一个 C++ 包装源码，里面内嵌脚本内容，
 *   编译后得到的是一个「脚本启动器 ELF」：
 *     运行时把内嵌脚本写到临时文件，然后 exec 真正的 shell 执行。
 *
 * 所以产物性质是：
 *   · 脚本内容被编译进 ELF 的 .rodata（静态分析看不到明文脚本）
 *   · 运行时仍需系统有 sh（Android 都自带 /system/bin/sh，没问题）
 *
 * 编译链路：
 *   script.sh → 生成 wrapper.c → clang -target aarch64-linux-android33
 *             → 输出 PIE 可执行文件
 *
 * 完全跑在 App 私有目录，不需要 root / ADB。
 */
object SscCompiler {

    data class Result(
        val ok: Boolean,
        val outputPath: String = "",
        val sizeBytes: Long = 0,
        val log: String = "",
        val message: String = "",
    )

    /**
     * 编译脚本。
     *
     * @param ctx    Context
     * @param script 用户脚本文件
     * @param outDir 输出目录
     * @param onLog  日志回调（逐行）
     */
    fun compile(
        ctx: Context,
        script: File,
        outDir: File,
        onLog: (String) -> Unit = {},
    ): Result {
        val status = NdkEnv.check(ctx)
        if (!status.ready) {
            return Result(false, message = "编译环境未就绪：${status.reason}")
        }

        val scriptText = try {
            script.readText()
        } catch (e: Throwable) {
            return Result(false, message = "读取脚本失败：${e.message}")
        }

        if (scriptText.isBlank()) {
            return Result(false, message = "脚本为空")
        }

        // 生成输出文件名
        if (!outDir.exists() && !outDir.mkdirs()) {
            return Result(false, message = "无法创建输出目录")
        }

        val baseName = script.name.substringBeforeLast('.', script.name)
        val workDir = File(ctx.filesDir, "ssc_work")
        workDir.mkdirs()

        // ---- 生成 C++ 包装源码 ----
        val srcFile = File(workDir, "wrapper.c")
        try {
            val src = buildWrapperSource(scriptText)
            srcFile.writeText(src)
        } catch (e: Throwable) {
            return Result(false, message = "生成源码失败：${e.message}")
        }
        onLog("生成包装源码：" + srcFile.absolutePath + "（" + srcFile.length() + " 字节）")

        val outFile = File(outDir, baseName + ".elf")
        val linker = NdkEnv.findLinker()
        onLog("linker: " + (linker ?: "未找到，尝试直接执行"))

        // ---- 调用 clang ----
        // 关键：App 私有目录 noexec，clang 直接执行会 Permission denied。
        // 必须用 /system/bin/linker64 拉起（与 ShellObfuscator 同一做法）。
        val clangArgs = buildCommand(status, srcFile, outFile)
        val cmd = if (linker != null) {
            listOf(linker) + clangArgs
        } else {
            clangArgs
        }
        onLog("命令: " + cmd.joinToString(" "))

        val log = StringBuilder()
        val exitCode = runCommand(
            cmd = cmd,
            env = buildEnv(status),
            timeoutSec = 300,
            onLine = { line ->
                log.append(line).append('\n')
                onLog(line)
            }
        )

        if (exitCode != 0 || !outFile.exists()) {
            return Result(
                ok = false,
                log = log.toString(),
                message = "编译失败（exit=$exitCode）"
            )
        }

        // ---- 恢复可执行权限 ----
        try {
            outFile.setExecutable(true, false)
        } catch (_: Throwable) {
        }

        // ---- 验证是真 ELF ----
        val isElf = try {
            outFile.inputStream().use { i ->
                val b = ByteArray(4)
                i.read(b) == 4 && b[0] == 0x7F.toByte() &&
                    b[1] == 'E'.code.toByte() && b[2] == 'L'.code.toByte() &&
                    b[3] == 'F'.code.toByte()
            }
        } catch (_: Throwable) {
            false
        }

        if (!isElf) {
            return Result(false, log = log.toString(), message = "产物不是有效 ELF")
        }

        return Result(
            ok = true,
            outputPath = outFile.absolutePath,
            sizeBytes = outFile.length(),
            log = log.toString(),
            message = "编译成功"
        )
    }

    // ============================================================
    // 包装源码生成
    // ============================================================

    /**
     * 生成 C 包装源码。
     *
     * 设计：
     *   1. 脚本内容以 unsigned char 数组内嵌，编译进 .rodata
     *      → 静态字符串搜索看不到明文脚本
     *   2. 运行时写到私有目录临时文件，然后 fork+exec /system/bin/sh
     *   3. 脚本数据做简单异或，抬高一点静态分析门槛
     */
    private val HEX_UPPER = "0123456789ABCDEF".toCharArray()

    private fun buildWrapperSource(script: String): String {
        val bytes = script.toByteArray(Charsets.UTF_8)
        val sb = StringBuilder()

        // 生成异或后的字节数组
        sb.append("/* SSC wrapper generated by csdemo */\n")
        sb.append("#include <stdio.h>\n")
        sb.append("#include <stdlib.h>\n")
        sb.append("#include <string.h>\n")
        sb.append("#include <unistd.h>\n")
        sb.append("#include <sys/stat.h>\n")
        sb.append("#include <sys/wait.h>\n")
        sb.append("#include <errno.h>\n\n")

        sb.append("static const unsigned char g_data[] = {")

        // 性能关键：不要用 "0x%02X,".format() 逐字节拼。
        // 那样每个字节都会创建一个 String 对象，5MB 脚本就是 500 万个对象，
        // 直接 OOM（已实际踩到："Failed to allocate a 16777216 byte allocation"）。
        // 改成先算好缓冲区，一次写满。
        val hex = HEX_UPPER
        var buf = CharArray(64 * 1024)
        var bufPos = 0

        fun flush() {
            if (bufPos > 0) {
                sb.appendRange(buf, 0, bufPos)
                bufPos = 0
            }
        }

        fun put(c: Char) {
            if (bufPos >= buf.size) flush()
            buf[bufPos++] = c
        }

        val newline = charArrayOf('\n', ' ', ' ', ' ', ' ')

        for (i in bytes.indices) {
            if (i % 20 == 0) {
                for (c in newline) put(c)
            }
            val x = (bytes[i].toInt() xor 0x5A) and 0xFF
            put('0'); put('x')
            put(hex[x ushr 4])
            put(hex[x and 0x0F])
            put(',')
        }
        flush()

        sb.append("\n    0x00\n};\n\n")
        sb.append("static const unsigned long g_len = ").append(bytes.size).append("UL;\n\n")

        sb.append(
            """
int main(int argc, char **argv) {
    /* 解密脚本 */
    unsigned char *buf = (unsigned char *)malloc(g_len + 1);
    if (!buf) { perror("malloc"); return 1; }
    for (unsigned long i = 0; i < g_len; i++) {
        buf[i] = g_data[i] ^ 0x5A;
    }
    buf[g_len] = 0;

    /* 写到临时文件 */
    const char *tmpdir = getenv("TMPDIR");
    if (!tmpdir) tmpdir = "/data/local/tmp";
    char path[512];
    snprintf(path, sizeof(path), "%s/.ssc_%d.sh", tmpdir, (int)getpid());

    FILE *f = fopen(path, "wb");
    if (!f) {
        /* 临时目录不可写时退回当前目录 */
        snprintf(path, sizeof(path), "./.ssc_%d.sh", (int)getpid());
        f = fopen(path, "wb");
        if (!f) { perror("fopen"); free(buf); return 1; }
    }
    fwrite(buf, 1, g_len, f);
    fclose(f);
    free(buf);
    chmod(path, 0700);

    /* 组装参数：sh script [args...] */
    int total = argc + 1;
    char **args = (char **)malloc(sizeof(char *) * (total + 1));
    if (!args) { unlink(path); return 1; }
    args[0] = (char *)"/system/bin/sh";
    args[1] = path;
    for (int i = 1; i < argc; i++) args[i + 1] = argv[i];
    args[total] = NULL;

    pid_t pid = fork();
    if (pid == 0) {
        execv(args[0], args);
        _exit(127);
    }

    int st = 0;
    if (pid > 0) waitpid(pid, &st, 0);
    unlink(path);
    free(args);

    if (WIFEXITED(st)) return WEXITSTATUS(st);
    return 1;
}
""".trimIndent()
        )

        return sb.toString()
    }

    // ============================================================
    // 命令构建与执行
    // ============================================================

    private fun buildCommand(status: NdkEnv.Status, src: File, out: File): List<String> {
        val clang = status.clangPath
        val args = ArrayList<String>()
        args.add(clang)
        args.add("-target")
        args.add("aarch64-linux-android33")
        args.add("-O2")
        args.add("-s")             // strip 符号
        args.add("-fPIE")
        args.add("-pie")
        args.add("-o")
        args.add(out.absolutePath)
        args.add(src.absolutePath)

        // sysroot（如果有）
        if (status.sysroot.isNotBlank()) {
            args.add("--sysroot=" + status.sysroot)
        }
        return args
    }

    private fun buildEnv(status: NdkEnv.Status): Map<String, String> {
        val env = HashMap<String, String>()
        // 保留必要环境变量，避免 shell 相关问题
        env["PATH"] = "/system/bin:/system/xbin"
        env["HOME"] = "/data/local/tmp"
        env["TMPDIR"] = "/data/local/tmp"
        if (status.sysroot.isNotBlank()) {
            env["SYSROOT"] = status.sysroot
        }
        return env
    }

    /**
     * 执行命令。
     *
     * 关键：App 私有目录是 noexec，不能直接执行 clang。
     * 用 linker64 拉起：linker64 <clang路径> <参数...>
     * 这是 ShellObfuscator 已经验证过的做法。
     */
    private fun runCommand(
        cmd: List<String>,
        env: Map<String, String>,
        timeoutSec: Int,
        onLine: (String) -> Unit,
    ): Int {
        return try {
            val pb = ProcessBuilder(cmd)
            pb.redirectErrorStream(true)
            pb.environment().putAll(env)

            val p = pb.start()
            val finished = p.waitFor(timeoutSec.toLong(), TimeUnit.SECONDS)
            if (!finished) {
                p.destroyForcibly()
                onLine("超时，已终止：${timeoutSec}s")
                return -1
            }

            p.inputStream.bufferedReader().useLines { lines ->
                lines.forEach { onLine(it) }
            }
            p.exitValue()
        } catch (e: Throwable) {
            onLine("执行异常：${e.message ?: e.javaClass.simpleName}")
            -1
        }
    }
}
